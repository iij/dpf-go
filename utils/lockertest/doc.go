// Package lockertest は、utils.Locker の実装が契約を満たすかを機械的に確かめる手段と、
// 契約を満たす参照実装を提供する。
//
// 排他の意味論は細かい。再入できないこと、「まだ保持されている」と「保持者でない」を
// 区別すること、延長が保持の確認を兼ねること。これらを取り違えると、排他として機能しない
// ものが静かにできあがる。自分で utils.Locker を実装する場合は Run で確かめること。
//
// # 使い方
//
//	func TestMyLocker(t *testing.T) {
//		lockertest.Run(t, func(t *testing.T) (utils.Locker, utils.Locker) {
//			// 同じ対象に対する排他を 2 つ返す
//			return newMyLocker("zone-1"), newMyLocker("zone-1")
//		})
//	}
//
// 2 つ返すのは、契約の中心が「一方が保持している間はもう一方が取得できない」ことだから
// である。1 つでは競合を確かめられない。
//
// # 参照実装
//
// Memory はプロセス内で完結する参照実装である。契約を満たしており、Run 自身の確認にも、
// 自分で実装を書くときの手本にも使える。**分散ロックの難しさは再現しない。** ネットワークの
// 分断も、保持期間の失効による奪い合いも起こらない。実物の仕組みに対する適合は、
// そのミドルウェアに対して確かめること。
//
// # 別パッケージにしている理由
//
// 本パッケージは testing を import する。これを utils に置くと、utils を使うすべての
// 利用者のバイナリにテスト用のフラグが登録される。標準ライブラリが net/http/httptest を
// 分けているのと同じ理由で分けている。
