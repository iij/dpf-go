// Command checklicenses は、依存モジュールのライセンスを許容リストと
// 照合する。
//
// # 母集団
//
// 判定の母集団は「実際に import されるパッケージ」である。宣言されているが
// import されていない依存を含むモジュールグラフ全体は用いない。これは本
// コマンドの都合ではなく憲章の規範であり、GPL 系を排除する根拠が「依存が
// 利用者のバイナリへ静的リンクされること」にあるためである。リンクされない
// 依存は利用者の配布物に条件を及ぼさない。逆にモジュールグラフ全体には
// 依存のテスト専用依存や未使用の依存が含まれ、実害のない偽陽性でゲートを
// 止める。ゲートが偽陽性で止まれば抑制の運用が始まり、抑制が増えれば
// ゲートの意味が失われる。
//
// # 入力
//
// go-licenses csv の出力を標準入力から受ける。1 行 1 パッケージ、
// カンマ区切りの 3 列（パッケージパス, ライセンス本文の URL, SPDX 識別子）
// とする。判別不能は 3 列目が Unknown になる。列数の異なる行はエラーとする。
// 無視すると、上流の出力形式が変わったことを「違反なし」に見せてしまう。
//
// どのモジュールの依存かは入力に含まれないため、引数で与える。
//
// 使い方:
//
//	go-licenses csv ./... | go run ./tools/checklicenses -module . -allowlist licenses-allowlist.txt
//
// -module にはリポジトリルートからの相対パスを渡す。"." を渡した場合は
// 本体モジュールとして扱い、ソース提供義務を伴うライセンスを違反とする。
//
// # 出力と終了コード
//
// 違反は「モジュール<TAB>パッケージ<TAB>区分<TAB>ライセンス<TAB>詳細」の
// 形で全件を標準出力へ出す。ソース提供義務を伴う依存は、違反が無くても
// 一覧として出す。この一覧は終了コードに影響しない。
//
//	0  違反なし
//	1  違反あり
//	2  検査できなかった（許容リストの読み込み失敗、入力の形式不正など）
//
// 1 と 2 を分けるのは対応が違うためである。前者は依存を直す。後者は環境か
// 入力を直す。検査できなかったことを「違反なし」として扱ってはならない。
//
// 本コマンドは検査のみを行い、ファイルを書き換えない。
