// Command checkheaders は、リポジトリ内のすべての Go ファイルについて、
// ファイル冒頭の規約が守られているかを検査する。
//
// 検査する規約は 2 つある。
//
//  1. 先頭行が「// SPDX-License-Identifier: Apache-2.0」であること。
//     テストファイル、ビルドタグによって既定のビルド対象から外れるファイル、
//     および生成物も対象とする。ファイルが切り出されて別の場所へ置かれた
//     ときにも由来が追えるようにするため、LICENSE ファイルではなく
//     ファイル単位で必須とする。
//  2. package 宣言より前に nolint 指示が置かれていないこと。
//     この位置にある nolint はファイル全体に効く。golangci-lint の
//     nolintlint は理由と対象 linter を伴う指示を通してしまうため、
//     範囲の広さはここで検査する。対象行に限定された nolint は
//     本コマンドの対象ではなく、理由の有無は nolintlint が扱う。
//
// vendor と testdata の配下は検査しない。前者は依存の持ち込み、
// 後者はテスト用の入力であり、本リポジトリのライセンス表記の対象ではない。
//
// 使い方:
//
//	go run ./tools/checkheaders [ディレクトリ]
//
// 引数を省略した場合はカレントディレクトリを起点に走査する。
//
// 終了コードは次のとおり。
//
//	0  違反なし
//	1  違反あり。違反したファイルをすべて標準出力へ列挙する
//	2  検査できなかった（走査や読み込みの失敗）
//
// 1 と 2 を分けるのは対応が違うためである。前者はファイルを直す。
// 後者は環境を直す。検査できなかったことを「違反なし」として扱ってはならない。
//
// 本コマンドは検査のみを行い、ファイルを書き換えない。
