// Command manual は、ゾーン単位の排他を同一のアクセストークンを用いる複数の
// プロセスから同時に取得しようとしたときの挙動を手動で確認する。
//
// specs/006-zone-lock-redesign の SC-001「同一のアクセストークンを用いる複数の
// プログラムが同じゾーンへ同時に取得を試みたとき、同時に成立する排他が 2 つ以上に
// なる事象が 0 件である」に対応する。
//
// 統合テスト（internal/integration）は API 呼び出しを直列化する制約
// （-parallel 1、同時実行数 1、1.1 秒に 1 リクエスト）を持つため、同時取得の確認と
// 両立しない。このため手動の手順として分けている。
//
// # 使い方
//
// 環境変数は統合テストと同じものを使う。DPF_TOKEN_RW と DPF_TEST_SERVICE_CODE が
// 必須で、DPF_API_ENDPOINT は任意である。
//
//	go build -o /tmp/dpflock ./internal/integration/manual
//	AT=$(date -u -d '+5 seconds' +%Y-%m-%dT%H:%M:%S.%NZ)
//	/tmp/dpflock -at "$AT" & /tmp/dpflock -at "$AT" & wait
//
// -at には全プロセスへ同じ時刻を渡す。各プロセスは接続の確立とゾーンの解決まで
// 済ませてからその時刻まで待ち、同時に取得を試みる。開始をそろえないと、競合させたい
// 区間（SOA のラベルを読んでから専用レコードを追加するまで）がすれ違ってしまう。
//
// 出力のうち acquired=true が 1 行だけであれば期待どおりである。2 行以上あれば
// 排他が成立していない。
//
// # 安全のための仕組み
//
// 書き込み対象ゾーンの特定は internal/integration の writeZone と同じ二重確認を行う。
// サービスコードから解決したゾーン名がコード上の定数と一致しなければ、何も行わずに
// 終了する。更新系のリトライは無効にし、レート制限は 1 秒あたり 2 リクエストに抑える。
//
// 取得できたプロセスは、解放の後に SOA レコードの未反映編集を破棄してゾーンを元の
// 状態へ戻す（-cleanup=false で無効化できる）。途中で強制終了した場合は、排他は
// -ttl の経過、専用レコードは失効時刻の経過によって解ける。残った場合は次の
// make test-integration が開始時に破棄する。
